const assert = require('node:assert/strict');
const fs = require('node:fs');
const {amount, select, matchesClaim, studioAmount} = require('../../js/nutrient-explorer.js');
const html=fs.readFileSync('nutrient-density-explorer.html','utf8');
const {rows,source}=JSON.parse(html.match(/<script type="application\/json">({"+rows"[^<]+)<\/script>/)[1]);
assert.equal(source,'https://fdc.nal.usda.gov/download-datasets/');
const base={nutrient:'magnesium', basis:'100g', category:'', query:' black beans ', includeUnknown:true};
const [beans]=select(rows,base);
assert.equal(beans.amount,70);
assert.equal(amount(beans,'magnesium','portion'),120.4);
assert(Math.abs(amount(beans,'f','100kcal') - 6.59090909)<1e-6);
assert.equal(select(rows,{...base, category:'Nuts & seeds'}).length,0);
assert.equal(select(rows,{...base, query:'',category:'Nuts & seeds'}).length,2);
const missing={...beans,values:{cal:0,f:null,magnesium:0,name:'fixture'},portion:null};
assert.equal(amount(missing,'f','100g'),null);
assert.equal(amount(missing,'magnesium','100g'),0);
assert.equal(amount(missing,'magnesium','100kcal'),null);
assert.equal(amount(missing,'magnesium','portion'),null);
assert.equal(select([missing],{...base, nutrient:'f', includeUnknown:false}).length,0);
assert.equal(select([missing],{...base, nutrient:'f', includeUnknown:true})[0].amount,null);
assert(matchesClaim('Raw milk and pasteurization', 'Food safety', '  RAW pasteurization ', 'Food safety'));
assert(!matchesClaim('Raw milk and pasteurization', 'Food safety', 'raw', 'Recovery'));
assert(!matchesClaim('A caffeine trial', 'Recovery', 'caffeine magnesium', ''));
const studioData = html.match(/<script type="application\/json">({"pairs":[^<]+)<\/script>/);
const [chicken, oats, pizza] = JSON.parse(studioData[1]).pairs;
assert.equal(studioAmount(chicken.sides[0],'cal','portion'),310);
assert.equal(studioAmount(chicken.sides[1],'cal','portion'),570);
assert.equal(studioAmount(chicken.sides[0],'na','portion'),1210);
assert.equal(studioAmount(oats.sides[0],'p','100g'),2.54);
assert.deepEqual(oats.sides[1].referenceIds,[173905,170886]);
assert.deepEqual(oats.sides[1].sources,[source]);
assert.equal(studioAmount(pizza.sides[1],'cal','portion'),1400);
assert.equal(studioAmount(pizza.sides[1],'cal','100g'),null);
assert.equal(studioAmount(pizza.sides[1],'p','portion'),null);
assert.equal(studioAmount(pizza.sides[1],'p','100kcal'),null);
console.log('PASS source basis, serving conversion, fixed calories, filter intersections and missing vs zero.');
