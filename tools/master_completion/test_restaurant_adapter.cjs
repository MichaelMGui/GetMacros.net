'use strict';
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs');
const root=path.resolve(__dirname,'../..'),F=require(path.join(root,'js/food-core.js'));
const rows=JSON.parse(fs.readFileSync(path.join(root,'tools/master_completion/restaurant_records.json'),'utf8')).records;
let checks=0;
const verify=(fn)=>{fn();checks++};
const fries=rows.find(r=>r.name==='Fries, Snack'),record=F.restaurant(fries);
verify(()=>assert.equal(record.market,'CA'));
verify(()=>assert.equal(record.sourcePublished,'2026-08-20'));
verify(()=>assert.equal(record.sourceChecked,'2026-10-13'));
verify(()=>assert.equal(record.sourceUrl,fries.source));
verify(()=>assert.equal(record.version,fries.sourceVersion));
verify(()=>assert.equal(record.portions[0].grams,170));
verify(()=>assert.equal(record.nutrients.potassium,1400));
verify(()=>assert.equal(record.nutrients.calcium,50));
verify(()=>assert.equal(record.nutrients.iron,1.75));
verify(()=>assert.equal(record.nutrients.magnesium,null));
verify(()=>assert.equal(F.scale(record,17,'g').cal,49));
verify(()=>assert.equal(F.scale(record,17,'g').potassium,140));
verify(()=>assert.equal(F.scale(record,2,'serving').calcium,100));
verify(()=>assert.equal(F.scale(record,17,'g').magnesium,null));
const saved=F.snapshot(record,17,'g');
verify(()=>assert.equal(saved.market,'CA'));
verify(()=>assert.equal(saved.sourcePublished,'2026-08-20'));
verify(()=>assert.equal(saved.sourceNutrients.potassium,1400));
verify(()=>assert.equal(saved.nutrients.potassium,140));
verify(()=>assert.equal(F.fromSnapshot(saved).portions[0].grams,170));
verify(()=>assert.equal(F.fromSnapshot(saved).nutrients.potassium,1400));
const mismatch=structuredClone(fries);
mismatch.additionalNutrients.potassium={unit:'g',value:1.4};
mismatch.additionalNutrients.calcium={unit:'mg',value:0};
mismatch.additionalNutrients.iron={unit:'mg',value:-1};
mismatch.additionalNutrients.vitaminA={unit:'mg',value:1};
const guarded=F.restaurant(mismatch);
verify(()=>assert.equal(guarded.nutrients.potassium,null));
verify(()=>assert.equal(guarded.nutrients.calcium,0));
verify(()=>assert.equal(guarded.nutrients.iron,null));
verify(()=>assert.equal(guarded.nutrients.vitaminA,null));
verify(()=>assert.equal(F.scale(guarded,2,'serving').potassium,null));
verify(()=>assert.equal(F.scale(guarded,2,'serving').calcium,0));
const micronutrients=structuredClone(fries);
micronutrients.additionalNutrients.selenium={unit:'µg',value:12};
micronutrients.additionalNutrients.vitaminD={unit:'µg',value:0};
micronutrients.additionalNutrients.folate={unit:'mg',value:.04};
micronutrients.additionalNutrients.magnesium={unit:'mg',value:20};
const micro=F.restaurant(micronutrients);
verify(()=>assert.equal(micro.nutrients.selenium,12));
verify(()=>assert.equal(F.scale(micro,2,'serving').selenium,24));
verify(()=>assert.equal(micro.nutrients.vitaminD,0));
verify(()=>assert.equal(micro.nutrients.folate,null));
verify(()=>assert.equal(micro.nutrients.magnesium,20));
const foods=rows.map(F.restaurant);
verify(()=>assert.equal(F.search(foods,'New York Fries',{market:'US',type:'restaurant'}).length,0));
verify(()=>assert.equal(F.search(foods,'Classic Poutine',{market:'JP',type:'restaurant'}).length,0));
verify(()=>assert.ok(F.search(foods,'Classic Poutine',{market:'CA',type:'restaurant'}).every(r=>r.market==='CA')));
verify(()=>assert.equal(F.search(foods,'Fries Snack',{market:'CA',type:'restaurant',restaurant:'Subway'}).length,0));
console.log(JSON.stringify({checks,source:'New York Fries Canadian reviewed fixture plus explicit unit-boundary cases',status:'passed'}));
